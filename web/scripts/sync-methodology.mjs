// Sync methodology/*.md from the repo root into a TS module the web app imports.
//
// Local development: this script runs on `predev` / `prebuild` / `typecheck`
// to regenerate `web/lib/methodology-content.ts` from the source files in
// `../methodology/`. Edit a .md file, save, the dev server picks up the change.
//
// Vercel deploy: Vercel only deploys the `web/` subdirectory, so
// `../methodology/` doesn't exist in the build environment. In that case we
// SKIP — the generated `methodology-content.ts` file is committed to git, so
// the build can proceed without regenerating it. The trade-off (a generated
// file in version control) is documented in the .gitignore.
//
// To update methodology in production: edit the .md files, run
// `pnpm sync:methodology` locally, commit both the .md change and the
// regenerated .ts file in the same commit, push.

import { existsSync, readFileSync, readdirSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const REPO_ROOT = join(__dirname, "..", "..");
const METHODOLOGY_DIR = join(REPO_ROOT, "methodology");
const OUTPUT_PATH = join(__dirname, "..", "lib", "methodology-content.ts");

// If we're running outside the repo (e.g. on Vercel where only web/ is
// deployed), skip the regeneration — the committed TS file is what gets used.
if (!existsSync(METHODOLOGY_DIR)) {
  if (existsSync(OUTPUT_PATH)) {
    console.log(
      `sync-methodology: methodology/ not present (likely a deploy build); ` +
        `using committed lib/methodology-content.ts as-is.`,
    );
    process.exit(0);
  } else {
    console.error(
      `sync-methodology: methodology/ not found at ${METHODOLOGY_DIR}, and ` +
        `committed output ${OUTPUT_PATH} is also missing. Cannot build.`,
    );
    process.exit(1);
  }
}

// Frontmatter parser — minimal YAML-style (top-of-file --- block).
function parseFrontmatter(raw) {
  if (!raw.startsWith("---")) return { frontmatter: {}, body: raw };
  const end = raw.indexOf("\n---", 3);
  if (end === -1) return { frontmatter: {}, body: raw };
  const fmText = raw.slice(3, end).trim();
  const body = raw.slice(end + 4).trimStart();

  const frontmatter = {};
  let currentKey = null;
  let currentArray = null;
  for (const line of fmText.split("\n")) {
    if (line.startsWith("  - ")) {
      // list item under the previous key
      if (currentArray) {
        currentArray.push(stripQuotes(line.slice(4).trim()));
      }
      continue;
    }
    const m = line.match(/^([a-z_]+):\s*(.*)$/i);
    if (!m) continue;
    const key = m[1];
    const value = m[2].trim();
    if (value === "" || value === ">") {
      // multiline or list-start
      currentKey = key;
      currentArray = [];
      frontmatter[key] = currentArray;
    } else {
      frontmatter[key] = stripQuotes(value);
      currentKey = null;
      currentArray = null;
    }
  }
  return { frontmatter, body };
}

function stripQuotes(s) {
  if ((s.startsWith('"') && s.endsWith('"')) || (s.startsWith("'") && s.endsWith("'"))) {
    return s.slice(1, -1);
  }
  return s;
}

// Slug = filename without .md
function slugFromFilename(name) {
  return name.replace(/\.md$/, "");
}

// --- main ---

const files = readdirSync(METHODOLOGY_DIR)
  .filter((f) => f.endsWith(".md"))
  .sort(); // 00-, 01-, ... ordering

if (files.length === 0) {
  console.error(`No .md files found in ${METHODOLOGY_DIR}`);
  process.exit(1);
}

const entries = files.map((filename) => {
  const slug = slugFromFilename(filename);
  const raw = readFileSync(join(METHODOLOGY_DIR, filename), "utf-8");
  const { frontmatter, body } = parseFrontmatter(raw);
  return { slug, filename, frontmatter, body };
});

// Generate the TS module
const tsModule = `// AUTO-GENERATED by scripts/sync-methodology.mjs — do not edit by hand.
// Re-run \`pnpm sync:methodology\` (or trigger \`pnpm dev\` / \`pnpm build\`) to refresh.

export interface MethodologyEntry {
  slug: string;
  filename: string;
  title: string;
  summary: string;
  body: string;
  primary_sources: string[];
  audience: string | null;
  framework: string | null;
  framing: string | null;
  related_implementations: string[];
}

export const METHODOLOGY_ENTRIES: MethodologyEntry[] = ${JSON.stringify(
  entries.map((e) => ({
    slug: e.slug,
    filename: e.filename,
    title: e.frontmatter.title ?? e.slug,
    summary: e.frontmatter.summary ?? "",
    body: e.body,
    primary_sources: Array.isArray(e.frontmatter.primary_sources)
      ? e.frontmatter.primary_sources
      : [],
    audience: typeof e.frontmatter.audience === "string" ? e.frontmatter.audience : null,
    framework: typeof e.frontmatter.framework === "string" ? e.frontmatter.framework : null,
    framing: typeof e.frontmatter.framing === "string" ? e.frontmatter.framing : null,
    related_implementations: Array.isArray(e.frontmatter.related_implementations)
      ? e.frontmatter.related_implementations
      : [],
  })),
  null,
  2,
)};

export function getEntryBySlug(slug: string): MethodologyEntry | undefined {
  return METHODOLOGY_ENTRIES.find((e) => e.slug === slug);
}
`;

// Ensure output directory exists
mkdirSync(dirname(OUTPUT_PATH), { recursive: true });
writeFileSync(OUTPUT_PATH, tsModule, "utf-8");

// Also emit a lightweight count constant so UI surfaces (landing CTA, OG
// image, page metadata) can show the writeup count WITHOUT importing the
// heavy full-content module. This is the single source of truth for the
// count — it can't drift across surfaces the way the old hardcoded 16/21
// strings did.
const COUNT_PATH = join(__dirname, "..", "lib", "methodology-count.ts");
const countModule = `// AUTO-GENERATED by scripts/sync-methodology.mjs — do not edit by hand.
// The number of methodology writeups in methodology/. Import this instead of
// hardcoding a count (it drifted to 16/21 against an actual 22 before this).
export const METHODOLOGY_COUNT = ${entries.length};
`;
writeFileSync(COUNT_PATH, countModule, "utf-8");

console.log(
  `synced ${entries.length} methodology files → lib/methodology-content.ts ` +
    `+ lib/methodology-count.ts (${entries.map((e) => e.slug).join(", ")})`,
);
